package store

import (
	"context"
	"crypto/rand"
	"crypto/sha256"
	"database/sql"
	"encoding/base64"
	"encoding/hex"
	"errors"
	"strings"
	"time"
	"unicode"
)

const (
	GrantTokenPrefix = "tunn_grant_"
	MaxGrantLifetime = 30 * 24 * time.Hour
	MaxGrantRequests = 1_000_000
)

var (
	ErrInvalidGrant          = errors.New("invalid grant parameters")
	ErrGrantNotOwned         = errors.New("endpoint not active or not owned by account")
	ErrGrantScopeUnsupported = errors.New("grants require a registered HTTP MCP endpoint")
)

// Grant is owner-visible metadata. Neither the bearer token nor its digest is
// included: the raw credential is returned only by Create.
type Grant struct {
	ID           string    `json:"id"`
	AccountID    string    `json:"-"`
	EndpointID   string    `json:"endpoint_id"`
	Label        string    `json:"label"`
	CreatedAt    time.Time `json:"created_at"`
	ExpiresAt    time.Time `json:"expires_at"`
	RequestLimit int64     `json:"request_limit"`
	Used         int64     `json:"used"`
	Revoked      bool      `json:"revoked"`
}

type GrantCreate struct {
	AccountID    string
	EndpointID   string
	Label        string
	ExpiresAt    time.Time
	RequestLimit int64
}

func (q GrantCreate) Validate(now time.Time) error {
	if !validGrantOwner(q.AccountID) || q.EndpointID == "" || len(q.EndpointID) > 253 || strings.TrimSpace(q.EndpointID) != q.EndpointID || len(q.Label) > 120 || strings.ContainsFunc(q.Label, unicode.IsControl) || !q.ExpiresAt.After(now) || q.ExpiresAt.After(now.Add(MaxGrantLifetime)) || q.RequestLimit < 1 || q.RequestLimit > MaxGrantRequests {
		return ErrInvalidGrant
	}
	return nil
}

// AccountID and EndpointID must come from the matched publisher, and RequestID
// must be generated by the relay. Caller-supplied IDs would bypass the allowance
// by replaying an earlier admission.
type GrantAdmissionRequest struct {
	AccountID  string
	EndpointID string
	Token      string
	RequestID  string
}

type GrantAdmission struct {
	Allowed bool
	GrantID string
	Reason  string
	Status  int
}

type GrantStore struct{ db *sql.DB }

func NewGrantStore(db *sql.DB) *GrantStore { return &GrantStore{db: db} }

func validGrantOwner(accountID string) bool { return accountID != "" && len(accountID) <= 128 }

func grantRandom(n int) (string, error) {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(b), nil
}

func grantDigest(token string) string {
	digest := sha256.Sum256([]byte(token))
	return hex.EncodeToString(digest[:])
}

// CanonicalAccountID resolves cached owner IDs after account merges, and rejects
// missing accounts. Alias rows are flattened by AccountStore.mergeAccounts.
func (s *GrantStore) CanonicalAccountID(ctx context.Context, accountID string) (string, error) {
	var canonical string
	err := s.db.QueryRowContext(ctx, `SELECT id FROM accounts WHERE id=COALESCE((SELECT account_id FROM account_aliases WHERE alias_id=?),?)`, accountID, accountID).Scan(&canonical)
	return canonical, err
}

func (s *GrantStore) Create(ctx context.Context, q GrantCreate) (*Grant, string, error) {
	now := time.Now().UTC()
	if err := q.Validate(now); err != nil {
		return nil, "", err
	}
	id, err := grantRandom(18)
	if err != nil {
		return nil, "", err
	}
	secret, err := grantRandom(32)
	if err != nil {
		return nil, "", err
	}
	token := GrantTokenPrefix + secret
	g := &Grant{ID: id, EndpointID: q.EndpointID, Label: q.Label, CreatedAt: now, ExpiresAt: q.ExpiresAt.UTC(), RequestLimit: q.RequestLimit}
	// Resolve ownership in the INSERT statement so an account merge cannot fall
	// between resolution and persistence. Missing accounts produce no row.
	err = s.db.QueryRowContext(ctx, `INSERT INTO endpoint_grants(id,account_id,endpoint_id,label,token_digest,created_at,expires_at,request_limit)
	 SELECT ?,id,?,?,?,?,?,? FROM accounts WHERE id=COALESCE((SELECT account_id FROM account_aliases WHERE alias_id=?),?) RETURNING account_id`,
		id, g.EndpointID, g.Label, grantDigest(token), now.UnixMilli(), g.ExpiresAt.UnixMilli(), g.RequestLimit, q.AccountID, q.AccountID).Scan(&g.AccountID)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, "", ErrGrantNotOwned
	}
	if err != nil {
		return nil, "", err
	}
	return g, token, nil
}

const grantColumns = `id,COALESCE((SELECT account_id FROM account_aliases WHERE alias_id=g.account_id),g.account_id),endpoint_id,label,created_at,expires_at,request_limit,used,revoked`

func scanGrant(row interface{ Scan(...any) error }) (*Grant, error) {
	g := &Grant{}
	var createdAt, expiresAt int64
	if err := row.Scan(&g.ID, &g.AccountID, &g.EndpointID, &g.Label, &createdAt, &expiresAt, &g.RequestLimit, &g.Used, &g.Revoked); err != nil {
		return nil, err
	}
	g.CreatedAt = time.UnixMilli(createdAt).UTC()
	g.ExpiresAt = time.UnixMilli(expiresAt).UTC()
	return g, nil
}

func (s *GrantStore) List(ctx context.Context, accountID, endpointID string) ([]Grant, error) {
	if !validGrantOwner(accountID) || len(endpointID) > 253 {
		return nil, ErrInvalidGrant
	}
	rows, err := s.db.QueryContext(ctx, `SELECT `+grantColumns+` FROM endpoint_grants g WHERE
	 COALESCE((SELECT account_id FROM account_aliases WHERE alias_id=g.account_id),g.account_id)=COALESCE((SELECT account_id FROM account_aliases WHERE alias_id=?),?)
	 AND (?='' OR endpoint_id=?) ORDER BY created_at,id`, accountID, accountID, endpointID, endpointID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := make([]Grant, 0)
	for rows.Next() {
		g, err := scanGrant(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, *g)
	}
	return out, rows.Err()
}

// Revoke is idempotent and owner scoped. A successful acknowledgement means
// later admissions cannot pass, including retries of an earlier reservation.
// Calls admitted before revocation may finish; admission is never refunded.
func (s *GrantStore) Revoke(ctx context.Context, accountID, grantID string) (bool, error) {
	if !validGrantOwner(accountID) || grantID == "" || len(grantID) > 64 {
		return false, ErrInvalidGrant
	}
	result, err := s.db.ExecContext(ctx, `UPDATE endpoint_grants AS g SET revoked=1 WHERE id=? AND
	 COALESCE((SELECT account_id FROM account_aliases WHERE alias_id=g.account_id),g.account_id)=COALESCE((SELECT account_id FROM account_aliases WHERE alias_id=?),?)`, grantID, accountID, accountID)
	if err != nil {
		return false, err
	}
	n, err := result.RowsAffected()
	return n > 0, err
}

func grantDenied(reason, id string, status int) *GrantAdmission {
	return &GrantAdmission{GrantID: id, Reason: reason, Status: status}
}

// Admit durably reserves one request before the relay forwards it. The first
// statement takes SQLite's write lock before reads, preventing concurrent
// transactions from oversubscribing the allowance. Ambiguous RPC retries reuse
// a reservation only for the same grant while it is still live.
func (s *GrantStore) Admit(ctx context.Context, q GrantAdmissionRequest) (*GrantAdmission, error) {
	if !validGrantOwner(q.AccountID) || q.EndpointID == "" || len(q.EndpointID) > 253 || q.RequestID == "" || len(q.RequestID) > 64 {
		return nil, ErrInvalidGrant
	}
	if !strings.HasPrefix(q.Token, GrantTokenPrefix) || len(q.Token) != len(GrantTokenPrefix)+43 {
		return grantDenied("grant_invalid", "", 401), nil
	}
	conn, err := s.db.Conn(ctx)
	if err != nil {
		return nil, err
	}
	defer conn.Close()
	// This pragma is per connection. A bounded wait handles ordinary concurrent
	// writers; cancellation/storage failures return errors and must fail closed.
	if _, err := conn.ExecContext(ctx, `PRAGMA busy_timeout=5000`); err != nil {
		return nil, err
	}
	tx, err := conn.BeginTx(ctx, nil)
	if err != nil {
		return nil, err
	}
	defer tx.Rollback()
	if _, err := tx.ExecContext(ctx, `UPDATE endpoint_grants SET used=used WHERE token_digest=?`, grantDigest(q.Token)); err != nil {
		return nil, err
	}
	g, err := scanGrant(tx.QueryRowContext(ctx, `SELECT `+grantColumns+` FROM endpoint_grants g WHERE token_digest=?`, grantDigest(q.Token)))
	if errors.Is(err, sql.ErrNoRows) {
		return grantDenied("grant_invalid", "", 401), nil
	}
	if err != nil {
		return nil, err
	}
	var canonical string
	err = tx.QueryRowContext(ctx, `SELECT id FROM accounts WHERE id=COALESCE((SELECT account_id FROM account_aliases WHERE alias_id=?),?)`, q.AccountID, q.AccountID).Scan(&canonical)
	if errors.Is(err, sql.ErrNoRows) {
		return grantDenied("grant_invalid", "", 401), nil
	}
	if err != nil {
		return nil, err
	}
	if canonical != g.AccountID || q.EndpointID != g.EndpointID {
		return grantDenied("grant_invalid", "", 401), nil
	}
	if g.Revoked {
		return grantDenied("grant_revoked", g.ID, 403), nil
	}
	now := time.Now().UTC()
	if !g.ExpiresAt.After(now) {
		return grantDenied("grant_expired", g.ID, 403), nil
	}
	var existingID string
	err = tx.QueryRowContext(ctx, `SELECT grant_id FROM grant_admissions WHERE request_id=?`, q.RequestID).Scan(&existingID)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return nil, err
	}
	if err == nil {
		if existingID != g.ID {
			return grantDenied("grant_invalid", "", 401), nil
		}
	} else {
		if g.Used >= g.RequestLimit {
			return grantDenied("grant_exhausted", g.ID, 429), nil
		}
		if _, err := tx.ExecContext(ctx, `UPDATE endpoint_grants SET used=used+1 WHERE id=?`, g.ID); err != nil {
			return nil, err
		}
		if _, err := tx.ExecContext(ctx, `INSERT INTO grant_admissions(request_id,grant_id,admitted_at) VALUES(?,?,?)`, q.RequestID, g.ID, now.UnixMilli()); err != nil {
			return nil, err
		}
	}
	if err := tx.Commit(); err != nil {
		return nil, err
	}
	return &GrantAdmission{Allowed: true, GrantID: g.ID, Reason: "grant", Status: 200}, nil
}
