#!/usr/bin/env python3
"""Render hosted CLI documentation from the built CLI, without account access."""
import argparse
import html
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
COMMANDS = [
    ('overview', ['--help']), ('http', ['http', '--help']),
    ('mcp', ['mcp', '--help']), ('connector-check', ['connector-check', '--help']),
    ('tcp', ['tcp', '--help']), ('unix', ['unix', '--help']),
    ('connect', ['connect', '--help']),
    ('share', ['share']), ('unshare', ['unshare']), ('access', ['access']),
    ('usage', ['usage', '--help']), ('grant', ['grant', '--help']),
    ('domain', ['domain', '--help']), ('keys', ['keys', '--help']),
    ('ip-policy', ['ip-policy', '--help']),
    ('service', ['service', 'install', '--help']),
    ('hosts', ['hosts', '--help']), ('openclaw', ['openclaw', '--help']),
    ('status-serve', ['status', 'serve', '--help']),
    ('status-incident', ['status', 'incident', '--help']),
    ('status-resolve', ['status', 'resolve', '--help']),
    ('admin', ['admin', '--help']),
]


def render(binary):
    parts = ['<!-- Generated by make docs-cli. Do not edit by hand. -->\n',
             '<p class="docs-label">Reference</p><h1>CLI reference</h1>\n',
             '<p class="docs-lead">Usage emitted by the built tunn binary.</p>\n',
             '<p>Regenerate with <code>make docs-cli</code>; verify with <code>make test-docs</code>. '
             'Global flags precede the subcommand. Serve flags can follow the target. '
             'Sharing commands have no separate help page; their usage below comes from invoking them without arguments. '
             'TCP, Unix and connect currently print a short usage on help. '
             'Service flags shown are for <code>service install</code>; run the chosen action with <code>--help</code>. '
             'Host-manifest defaults use Linux paths in this generated reference; check local help on macOS or Windows.</p>\n',
             '<p>' + ' · '.join(f'<a href="#{name}">{name}</a>' for name, _ in COMMANDS) + '</p>\n']
    # Help executes in an empty directory with isolated credentials/config. No .env is read.
    with tempfile.TemporaryDirectory(prefix='tunn-cli-docs-') as fixture:
        env = {'PATH': os.environ.get('PATH', ''), 'HOME': fixture,
               'XDG_CONFIG_HOME': fixture + '/.config', 'TUNN_ENV': 'prod', 'LANG': 'C'}
        for name, args in COMMANDS:
            result = subprocess.run([str(binary), *args], cwd=fixture, env=env,
                                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                    text=True, timeout=5)
            # Error-path help can include a clock-dependent log line. Keep only usage, not logs.
            output = '\n'.join(line for line in result.stdout.splitlines() if not line.startswith('time='))
            output = output.replace(fixture, '$HOME').strip().expandtabs(8)
            if result.returncode not in (0, 1, 2) or not output or not any(
                marker in output.lower() for marker in ('usage', 'tunn keys', 'tunn ip-policy', 'tunn admin')
            ):
                raise RuntimeError(f'{name}: help failed (exit {result.returncode}): {output}')
            command = 'tunn ' + ' '.join(args)
            parts.append(f'<section id="{name}"><h2>{html.escape(command)}</h2>\n'
                         f'<pre class="cli-help"><code>{html.escape(output)}</code></pre></section>\n')
    parts.append('<p class="docs-next"><a href="/docs/troubleshooting">Find an error message</a> · '
                 '<a href="/docs/limits">Pricing and limits</a></p>\n')
    return ''.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary', type=Path, default=ROOT / 'bin/tunn')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'internal/host/templates/docs-cli.html'
    content = render(args.binary.resolve())
    if args.check:
        if not destination.exists() or destination.read_text() != content:
            parser.exit(1, 'CLI docs differ from real help; run make docs-cli\n')
        print('CLI docs match real help (22 command entries)')
    else:
        destination.write_text(content)
        print(f'Generated {destination.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
